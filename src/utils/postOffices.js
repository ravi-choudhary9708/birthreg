// Fast lookup map by PIN code
export const POST_OFFICES_BY_PINCODE = MADHUBANI_POST_OFFICES.reduce((acc, po) => {
  if (!acc[po.pincode]) {
    acc[po.pincode] = [];
  }
  acc[po.pincode].push(po);
  return acc;
}, {});

/**
 * Returns list of Post Offices for a given PIN code.
 * Accepts any list (e.g. from database) or defaults to static master data.
 */
export function getPostOfficesForPincode(pincode, list) {
  if (!pincode) return [];
  const cleanPin = String(pincode).trim();
  if (cleanPin.length !== 6) return [];
  
  if (list && Array.isArray(list) && list.length > 0) {
    return list.filter((po) => String(po.pincode).trim() === cleanPin);
  }
  
  return POST_OFFICES_BY_PINCODE[cleanPin] || [];
}

/**
 * Validates whether a given PIN code is an official 6-digit Madhubani district PIN code.
 */
export function isValidMadhubaniPincode(pincode) {
  if (!pincode) return false;
  const cleanPin = String(pincode).trim();
  return /^[0-9]{6}$/.test(cleanPin) && cleanPin in POST_OFFICES_BY_PINCODE;
}

/**
 * Validates PIN code format and returns validation result object
 */
export function validatePincode(pincode) {
  if (!pincode) {
    return { isValid: false, message: 'पिनकोड अनिवार्य है (PIN Code is required)' };
  }
  const cleanPin = String(pincode).trim();
  if (!/^[0-9]{6}$/.test(cleanPin)) {
    return { isValid: false, message: 'पिनकोड 6 अंकों का होना चाहिए (PIN code must be exactly 6 digits)' };
  }
  if (!isValidMadhubaniPincode(cleanPin)) {
    return {
      isValid: false,
      isDistrictWarning: true,
      message: 'चेतावनी: यह पिनकोड मधुबनी जिले के आधिकारिक पिनकोड सूची में नहीं है। (Warning: PIN not in Madhubani list)',
    };
  }
  return { isValid: true, message: 'मान्य पिनकोड (Valid Madhubani PIN Code)' };
}
